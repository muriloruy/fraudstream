/**
 * `pnpm web:types` — generates apps/web/src/lib/api-types.ts from the alerts-gateway OpenAPI
 * document (SPEC §8.3), without starting the service: the document is built from the same
 * Zod schemas the gateway validates with.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
import { buildOpenApi } from '../apps/alerts-gateway/src/infrastructure/http/openapi.js';

const target = fileURLToPath(new URL('../apps/web/src/lib/api-types.ts', import.meta.url));
const ast = await openapiTS(buildOpenApi() as unknown as Parameters<typeof openapiTS>[0]);
const header =
  '// Generated by `pnpm web:types` from the alerts-gateway OpenAPI document. Do not edit.\n';
writeFileSync(target, header + astToString(ast));
console.log(`wrote ${target}`);
