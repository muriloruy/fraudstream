export const RETRY_RETENTION_MS = DAY_MS;
export const DLQ_RETENTION_MS = 30 * DAY_MS;
export const DLQ_PARTITIONS = 3;

/** `<topic>.<group>.retry` (SPEC §4.6). */
export const retryTopic = (topic: string, group: string): string => `${topic}.${group}.retry`;

/** `<topic>.<group>.dlq` (SPEC §4.6). */
export const dlqTopic = (topic: string, group: string): string => `${topic}.${group}.dlq`;

/** Every topic the cluster must have: sources plus a retry and a DLQ topic per (topic, group). */
export function allTopics(catalogue: readonly SourceTopicSpec[] = TOPIC_CATALOGUE): TopicSpec[] {
  const topics: TopicSpec[] = [];
  for (const source of catalogue) {
    const { consumerGroups: _groups, ...spec } = source;
    topics.push(spec);
    for (const group of source.consumerGroups) {
      topics.push({
        name: retryTopic(source.name, group),
        partitions: source.partitions,
        cleanupPolicy: 'delete',
        retentionMs: RETRY_RETENTION_MS,
      });
      topics.push({
        name: dlqTopic(source.name, group),
        partitions: DLQ_PARTITIONS,
        cleanupPolicy: 'delete',
        retentionMs: DLQ_RETENTION_MS,
      });
    }
  }
  return topics;
}

/**
 * Renders `infra/kafka/topics.conf`, read by `infra/kafka/init-topics.sh`.
 * Format: `<name> <partitions> <cleanup.policy> <retention.ms|-1>` per line.
 */
export function renderTopicsConf(topics: readonly TopicSpec[] = allTopics()): string {
  const header = [
    '# GENERATED by `pnpm topics:generate` from libs/contracts/src/topics.ts. Do not edit by hand.',
    '# name partitions cleanup.policy retention.ms(-1 = unlimited)',
  ];
  const lines = topics.map(
    (t) => `${t.name} ${t.partitions} ${t.cleanupPolicy} ${t.retentionMs ?? -1}`,
  );
  return [...header, ...lines, ''].join('\n');
}
